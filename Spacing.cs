namespace PromptGenerator;

/// <summary>间距常量（语义分组：Margin/Padding 统一取这里，避免 4/5 不一致）。</summary>
public static class Spacing
{
    /// <summary>2px：紧挨着。</summary>
    public const double Xs = 2;
    /// <summary>4px：小间距（默认行内间距）。</summary>
    public const double Sm = 4;
    /// <summary>8px：中间距（输入框内边距）。</summary>
    public const double Md = 8;
    /// <summary>12px：大间距。</summary>
    public const double Lg = 12;
}
